"""
Unit 4: MusicGen Generation Engine
Model: facebook/musicgen-small (configurable via MUSICGEN_MODEL)
Duration: Strictly 10-second clips (500 tokens at 50 Hz frame rate)
Execution: CPU optimized, torch.inference_mode, deterministic seeding
"""

import os
import sys
import time
from typing import Optional, Tuple, Callable

# Ensure OpenMP runtime conflict does not crash on Windows
os.environ["KMP_DUPLICATE_LIB_OK"] = "TRUE"

import numpy as np
import scipy.io.wavfile
import torch

# Global cached singletons for lazy loading
_MODEL = None
_PROCESSOR = None
_DEVICE = "cuda" if torch.cuda.is_available() else "cpu"


def get_model_id() -> str:
    """Return the configured MusicGen model identifier."""
    return os.getenv("MUSICGEN_MODEL", "facebook/musicgen-small")


def load_musicgen(progress_callback: Optional[Callable[[float, str], None]] = None):
    """
    Lazy singleton loader for MusicGen model and processor.
    Loads once on first use and caches in memory.
    """
    global _MODEL, _PROCESSOR, _DEVICE
    if _MODEL is not None and _PROCESSOR is not None:
        return _MODEL, _PROCESSOR, _DEVICE

    if progress_callback:
        progress_callback(0.05, "Loading MusicGen processor and weights...")

    from transformers import MusicgenForConditionalGeneration, AutoProcessor

    model_id = get_model_id()
    print(f"[MusicGen] Initializing {model_id} on {_DEVICE}...", flush=True)

    # Set CPU threads to available CPU count for optimal parallel matrix ops
    if _DEVICE == "cpu":
        cpu_threads = os.cpu_count() or 2
        torch.set_num_threads(cpu_threads)
        print(f"[MusicGen] Configured PyTorch CPU threads: {cpu_threads}", flush=True)

    try:
        _PROCESSOR = AutoProcessor.from_pretrained(model_id, local_files_only=True)
        _MODEL = MusicgenForConditionalGeneration.from_pretrained(model_id, local_files_only=True)
    except Exception:
        _PROCESSOR = AutoProcessor.from_pretrained(model_id)
        _MODEL = MusicgenForConditionalGeneration.from_pretrained(model_id)
    _MODEL.to(_DEVICE)
    _MODEL.eval()

    print(f"[MusicGen] Model successfully loaded on {_DEVICE}.", flush=True)
    return _MODEL, _PROCESSOR, _DEVICE


def get_musicgen_model_and_processor():
    """Returns model, processor, frame_rate, and native sampling rate."""
    model, processor, device = load_musicgen()
    frame_rate = getattr(model.config.audio_encoder, "frame_rate", 50)
    sampling_rate = getattr(model.config.audio_encoder, "sampling_rate", 32000)
    return model, processor, frame_rate, sampling_rate


def generate_music_clip(
    prompt: str,
    seed: int = 42,
    output_path: Optional[str] = None,
    progress_callback: Optional[Callable[[float, str], None]] = None,
    duration_seconds: float = 10.0,
) -> Tuple[np.ndarray, int, str]:
    """
    Generate a strictly 10.0-second audio clip from text prompt with a deterministic seed.

    Args:
        prompt: Natural language music description.
        seed: Random PRNG seed for reproducibility.
        output_path: Target .wav file path (optional; autogenerated if None).
        progress_callback: Optional callable for Gradio progress updates.

    Returns:
        Tuple of (audio_waveform_numpy, native_sampling_rate, saved_file_path)
    """
    if progress_callback:
        progress_callback(0.1, "Initializing MusicGen pipeline...")

    model, processor, device = load_musicgen(progress_callback)

    # Frame rate determines token count for exact 10.0-second generation
    # MusicGen frame rate is 50 Hz -> 10s * 50 Hz = 500 tokens
    frame_rate = getattr(model.config.audio_encoder, "frame_rate", 50)
    target_duration_s = duration_seconds
    max_new_tokens = int(target_duration_s * frame_rate)
    native_sr = getattr(model.config.audio_encoder, "sampling_rate", 32000)

    print(f"[MusicGen] Generating for prompt: '{prompt}' | Seed: {seed} | Tokens: {max_new_tokens}", flush=True)

    # Set seed deterministically for reproducibility
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    if progress_callback:
        progress_callback(0.2, "Tokenizing prompt...")

    inputs = processor(text=[prompt], padding=True, return_tensors="pt").to(device)

    start_time = time.time()
    if progress_callback:
        progress_callback(0.3, "Synthesizing audio autoregressively (this may take 1-2 min on CPU)...")

    with torch.inference_mode():
        audio_values = model.generate(
            **inputs,
            do_sample=True,
            guidance_scale=3.0,
            max_new_tokens=max_new_tokens,
        )

    elapsed = time.time() - start_time
    print(f"[MusicGen] Generation finished in {elapsed:.1f}s.", flush=True)

    # Convert tensor to numpy 1D float32 audio
    # audio_values shape: (batch_size, channels, sequence_length) -> typically (1, 1, 320000)
    audio_tensor = audio_values.squeeze().detach().cpu()
    audio_np = audio_tensor.numpy()

    # If stereo or multichannel, take first channel or average
    if audio_np.ndim > 1:
        audio_np = audio_np[0]

    # Validate duration strictly
    clip_duration = len(audio_np) / float(native_sr)
    print(f"[MusicGen] Output samples: {len(audio_np)} at {native_sr} Hz ({clip_duration:.2f}s)", flush=True)
    assert abs(clip_duration - target_duration_s) < 0.2, (
        f"Assertion Failed: Expected {target_duration_s}s clip, but received {clip_duration:.2f}s."
    )

    # Determine destination filepath
    if output_path is None:
        os.makedirs("results/audio", exist_ok=True)
        safe_prefix = "".join(c if c.isalnum() else "_" for c in prompt[:20]).strip("_")
        output_path = os.path.join("results", "audio", f"gen_{safe_prefix}_s{seed}_{int(time.time())}.wav")
    else:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

    # Write WAV using scipy at native sampling rate (float32 in [-1, 1])
    # Normalize if peak exceeds 1.0 to prevent clipping distortion
    peak = np.max(np.abs(audio_np))
    if peak > 1.0:
        audio_np = audio_np / peak

    scipy.io.wavfile.write(output_path, native_sr, (audio_np * 32767).astype(np.int16))
    print(f"[MusicGen] Saved WAV to {output_path}", flush=True)

    if progress_callback:
        progress_callback(1.0, "Audio generation complete.")

    return audio_np, native_sr, output_path
